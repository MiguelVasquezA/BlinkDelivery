--
-- BORRADOR: no se ha ejecutado en Supabase. Ejecútalo a mano después de 007.
-- Cada tabla recibe una identidad que empieza justo después del mayor ID existente,
-- así que no choca con los datos ya cargados.

-- 1. Categoría opcional del producto (los productos existentes quedan en NULL).
ALTER TABLE producto
    ADD COLUMN IF NOT EXISTS id_categoria INTEGER NULL
        REFERENCES categoria (id_categoria) ON DELETE SET NULL;

-- 2. Identidad en las llaves primarias de las tablas que migran primero.
DO $$
DECLARE
    destino RECORD;
    siguiente BIGINT;
BEGIN
    FOR destino IN
        SELECT * FROM (VALUES
            ('restaurante', 'id_restaurante'),
            ('categoria', 'id_categoria'),
            ('producto', 'id_producto'),
            ('calificacion', 'id_calificacion')
        ) AS t(tabla, columna)
    LOOP
        EXECUTE format('SELECT COALESCE(MAX(%I), 0) + 1 FROM %I', destino.columna, destino.tabla)
            INTO siguiente;
        EXECUTE format(
            'ALTER TABLE %I ALTER COLUMN %I ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)',
            destino.tabla, destino.columna, siguiente);
    END LOOP;
END $$;
